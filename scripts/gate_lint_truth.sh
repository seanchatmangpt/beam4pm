#!/usr/bin/env bash
# GATE LINT-TRUTH — a static overclaiming-phrase scanner, transplanted from
# ex4pm's `mix ex4pm.lint.truth` (apps/ex4pm_qualification/lib/mix/tasks/
# ex4pm.lint.truth.ex + lie_finder.ex) architecture: a standalone scanner
# that exits nonzero on any finding, wired as an early verify step. Only
# the ARCHITECTURE transplants -- ex4pm's actual rules are AST checks tied
# to its own BRCE/standing/fitness vocabulary and don't apply here; this is
# a grep-based scan over the banned-phrase list from
# ~/.claude/rules/no-overclaiming-rust.md, scoped to beam4pm's own
# hand-authored surfaces (never a GENERATED file -- those are ggen's
# output, not a claim anyone wrote by hand).
set -euo pipefail
cd "$(dirname "$0")/.."

# Banned phrases (case-insensitive extended regex). "production-ready" is
# banned only when unscoped (not immediately followed by "for ..."). BSD
# grep (macOS's /usr/bin/grep, which a plain `bash script.sh` invocation
# resolves to regardless of an interactive shell's own grep alias/PATH)
# has no -P/PCRE support, so this is checked with two portable ERE passes
# (find "production-ready", then subtract lines also matching
# "production-ready for") rather than a negative lookahead.
BASIC_PHRASES='substantially complete|should work|probably environmental|fully working|100% complete'
PROD_READY_ANY='production-ready'
PROD_READY_SCOPED='production-ready[[:space:]]+for'

SEARCH_DIRS=(docs README.md CLAUDE.md CONTRIBUTING.md)

find_hand_authored() {
  for d in "${SEARCH_DIRS[@]}"; do
    [ -e "$d" ] || continue
    if [ -f "$d" ]; then
      echo "$d"
    else
      find "$d" -type f \( -name "*.md" -o -name "*.ex" -o -name "*.erl" \) 2>/dev/null
    fi
  done | sort -u | while read -r f; do
    head -3 "$f" 2>/dev/null | grep -qi "GENERATED by ggen" || echo "$f"
  done
}

echo "== GATE LINT-TRUTH: scanning hand-authored docs/source for banned overclaiming phrases =="

mapfile -t files < <(find_hand_authored)
echo "scanning ${#files[@]} hand-authored files"

report="$(mktemp)"
trap 'rm -f "$report"' EXIT

if [ "${#files[@]}" -gt 0 ]; then
  grep -inE "$BASIC_PHRASES" "${files[@]}" </dev/null >> "$report" 2>/dev/null || true
  grep -inE "$PROD_READY_ANY" "${files[@]}" </dev/null 2>/dev/null \
    | grep -ivE "$PROD_READY_SCOPED" >> "$report" 2>/dev/null || true
fi

findings=$(wc -l < "$report" | tr -d ' ')

if [ "$findings" -gt 0 ]; then
  echo "REFUSED: banned overclaiming phrase(s) found:"
  sort -u "$report" | sed 's/^/  /'
  echo "GATE LINT-TRUTH: FAIL -- $findings banned-phrase finding(s)" >&2
  exit 1
fi

echo "GATE LINT-TRUTH: PASS -- ${#files[@]} hand-authored files scanned, 0 findings"
