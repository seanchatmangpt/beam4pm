#!/usr/bin/env bash
# GATE ENGINE DISPATCH -- every manufactured engine op must be an op the
# engine's crate actually dispatches, or the tree is refused.
#
# The four native-engine facade triples (src/beam4pm_<engine>.erl,
# lib/beam4pm_<engine>.ex, gleam/src/beam4pm/<engine>.gleam) are rendered by
# the vendored beam4pm-process-model-pack's templates/beam4pm_engine.*.tmpl
# from the consumer's bpm:Engine / bpm:EngineOp / bpm:EngineArg facts in
# ontology.ttl. Those facts are the source of truth for the FACADE, but the
# wire ops they name are only real if the crate's dispatch match has an arm
# for them: a fact naming an op the crate does not dispatch would render a
# perfectly compiling wrapper whose every call returns the engine's
# "unknown op" error -- a manufactured lie the parity suites would only
# catch if they happened to call that op. This gate makes the join
# mechanical and cheap: the pack also renders schema/beam4pm_engine_ops.tsv
# (one row per op: engine, op, wire_name, kind, dispatch_source), and this
# script greps each engine's bpm:dispatchSource for its string-literal
#     "<wire_name>" => ...        (single arm)
#     "<a>" | "<b>" => ...        (alternation arm -- split on |)
# match arms, exactly the shape all four crates use today.
#
# Refusals (typed lines, any one fails the gate):
#   REFUSED_MANIFEST_MISSING / REFUSED_MANIFEST_UNMANUFACTURED / REFUSED_MANIFEST_MALFORMED
#   REFUSED_OP_NOT_DISPATCHED   a `wire` row whose wire_name is not a dispatch arm
#   REFUSED_ENGINE_NOT_DISPATCHED  an engine whose dispatch source has zero arms
#                               (wrong bpm:dispatchSource path or crate shape)
# Reported, not refused:
#   DISPATCH_SOURCE_ABSENT      the crate source is not on disk (e.g. a git
#                               submodule not initialised) -- BLOCKED, not a pass
#   UNEXPOSED_DISPATCH_ARM      a crate arm no fact exposes (scope control: this
#                               increment exposes no new op, so this is expected
#                               and must stay visible rather than silently
#                               becoming a manufactured function)
#   host_helper rows are exempt from the arm check by kind (they File.read!
#   host-side and delegate to a wire op; the delegate is gate-checked in the
#   pack's gates/090 to be a wire op of the same engine).
#
# Portable to bash 3.2 on purpose (no mapfile, no associative arrays), same
# as scripts/gate_authorship_check.sh.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
MANIFEST=""
MARKER="GENERATED by ggen"

usage() {
  cat <<EOF
usage: bash scripts/gate_engine_dispatch_check.sh [--root DIR] [--manifest FILE]
  --root DIR       repo working tree to check (default: this repo)
  --manifest FILE  engine-op manifest (default: <root>/schema/beam4pm_engine_ops.tsv)
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --root) ROOT="$(cd "$2" && pwd)"; shift 2 ;;
    --manifest) MANIFEST="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "gate_engine_dispatch_check.sh: unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [ -z "$MANIFEST" ]; then
  MANIFEST="$ROOT/schema/beam4pm_engine_ops.tsv"
else
  case "$MANIFEST" in
    /*) ;;
    *) MANIFEST="$(pwd)/$MANIFEST" ;;
  esac
fi

cd "$ROOT"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
FINDINGS="$WORK/findings"
ROWS="$WORK/rows"
: > "$FINDINGS"

refuse() {
  if [ -n "${3:-}" ]; then
    echo "$1: $2 ($3)" >> "$FINDINGS"
  else
    echo "$1: $2" >> "$FINDINGS"
  fi
}

is_marked() {
  head -3 "$1" 2>/dev/null | grep -qi "$MARKER"
}

# Print one dispatch arm literal per line for a crate source: every
# double-quoted snake_case literal appearing on a line of the form
#   "lit" => ...   or   "lit" | "lit2" => ...
dispatch_arms() {
  # `|| true`: under set -o pipefail a source with ZERO arms would otherwise
  # abort the whole script here (grep exits 1 on no match) instead of reaching
  # the REFUSED_ENGINE_NOT_DISPATCHED refusal below -- caught by the planted
  # no-arms fixture in test/beam4pm_engine_dispatch_gate_test.exs.
  { grep -E '^[[:space:]]*"[a-z_0-9]+"([[:space:]]*\|[[:space:]]*"[a-z_0-9]+")*[[:space:]]*=>' "$1" 2>/dev/null || true; } \
    | sed -E 's/=>.*$//' \
    | tr '|' '\n' \
    | sed -E 's/^[[:space:]]*"//; s/"[[:space:]]*$//' \
    | { grep -v '^$' || true; } \
    | sort -u
}

echo "== GATE ENGINE DISPATCH: manufactured engine ops must be crate-dispatched ops =="
echo "root: $ROOT"
echo "manifest: $MANIFEST"

if [ ! -f "$MANIFEST" ]; then
  echo "REFUSED_MANIFEST_MISSING: $MANIFEST (regenerate: rm -f ggen.lock && ggen sync run)"
  echo "GATE ENGINE DISPATCH: FAIL -- engine-op manifest missing" >&2
  exit 1
fi
if ! is_marked "$MANIFEST"; then
  echo "REFUSED_MANIFEST_UNMANUFACTURED: $MANIFEST (no '$MARKER' marker in its first 3 lines)"
  echo "GATE ENGINE DISPATCH: FAIL -- engine-op manifest is not manufactured output" >&2
  exit 1
fi

# --- pass 1: parse the manufactured manifest ------------------------------
# Columns: engine op wire_name kind dispatch_source wasm_artifact
grep -v '^#' "$MANIFEST" | grep -v '^[[:space:]]*$' > "$ROWS" || true
while IFS=$'\t' read -r engine op wire kind src artifact extra; do
  if [ -z "$engine" ] || [ -z "$op" ] || [ -z "$wire" ] || [ -z "$kind" ] || [ -z "$src" ] || [ -z "$artifact" ] || [ -n "${extra:-}" ]; then
    refuse REFUSED_MANIFEST_MALFORMED "$engine/$op" "expected exactly 6 tab-separated columns"
    continue
  fi
  case "$kind" in wire|host_helper) ;; *) refuse REFUSED_MANIFEST_MALFORMED "$engine/$op" "kind must be wire or host_helper, got '$kind'" ;; esac
done < "$ROWS"
rows_n=$(wc -l < "$ROWS" | tr -d ' ')
engines_n=$(cut -f1 "$ROWS" | sort -u | wc -l | tr -d ' ')
echo "manifest: $rows_n ops across $engines_n engines"

# --- pass 2: per engine, join the wire rows against the crate's arms -------
blocked_n=0
checked_n=0
unexposed_n=0
cut -f1,5 "$ROWS" | sort -u > "$WORK/engines"
while IFS=$'\t' read -r engine src; do
  [ -n "$engine" ] || continue
  if [ ! -f "$src" ]; then
    echo "DISPATCH_SOURCE_ABSENT: $engine ($src not on disk -- initialise the submodule / check bpm:dispatchSource; BLOCKED, not a pass)"
    blocked_n=$((blocked_n + 1))
    continue
  fi
  dispatch_arms "$src" > "$WORK/arms.$engine" || true
  arms_n=$(wc -l < "$WORK/arms.$engine" | tr -d ' ')
  if [ "$arms_n" -eq 0 ]; then
    refuse REFUSED_ENGINE_NOT_DISPATCHED "$engine" "$src has no string-literal \"op\" => match arms; wrong bpm:dispatchSource or an unrecognised dispatch shape"
    continue
  fi
  awk -F'\t' -v e="$engine" '$1 == e && $4 == "wire" {print $3}' "$ROWS" | sort -u > "$WORK/wire.$engine"
  wire_n=$(wc -l < "$WORK/wire.$engine" | tr -d ' ')
  while IFS= read -r w; do
    [ -n "$w" ] || continue
    if ! grep -qxF -- "$w" "$WORK/arms.$engine"; then
      refuse REFUSED_OP_NOT_DISPATCHED "$engine/$w" "no \"$w\" => arm in $src -- the manufactured wrapper would compile and every call would return the engine's unknown-op error"
    fi
    checked_n=$((checked_n + 1))
  done < "$WORK/wire.$engine"
  comm -23 "$WORK/arms.$engine" "$WORK/wire.$engine" | while IFS= read -r a; do
    [ -n "$a" ] || continue
    echo "UNEXPOSED_DISPATCH_ARM: $engine/$a (crate dispatches it; no bpm:EngineOp exposes it -- scope control, reported not refused)"
  done
  unexposed_here=$(comm -23 "$WORK/arms.$engine" "$WORK/wire.$engine" | grep -c . || true)
  unexposed_n=$((unexposed_n + unexposed_here))
  echo "engine $engine: $wire_n wire ops checked against $arms_n dispatch arms in $src"
done < "$WORK/engines"

findings_n=$(wc -l < "$FINDINGS" | tr -d ' ')
if [ "$findings_n" -gt 0 ]; then
  echo "REFUSED: $findings_n finding(s):"
  sort -u "$FINDINGS" | sed 's/^/  /'
  echo "GATE ENGINE DISPATCH: FAIL -- $findings_n finding(s)" >&2
  exit 1
fi

echo "GATE ENGINE DISPATCH: PASS -- $checked_n wire ops dispatched across $engines_n engines, $unexposed_n crate arms unexposed (reported), $blocked_n engines blocked on absent sources, 0 findings"
