#!/usr/bin/env bash
# B4PM-1702 verification script: proves the single-record-patch codemod
# (mix ggen_igniter.patch_field) produces output byte-identical, for the
# touched BeamPM.Types.DfgEdge module, to a full ggen sync run from the
# same updated ontology.ttl -- and that every OTHER admitted bpm:RecordType
# is left with zero changes, proven against a real pre-patch baseline
# (the same "find manufactured-by-marker files, sha256 them" technique
# gate_m2_check.sh uses).
#
# Run from a worktree with ontology.ttl ALREADY carrying the one field
# addition (bpm:dfg_edge_edge_weight_f on bpm:dfg_edge_rt) this story
# picked -- this script does not itself edit the ontology.
set -euo pipefail
cd "$(dirname "$0")/.."

TARGET="lib/beam4pm_types.ex"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

echo "== 0. pre-patch baseline: sha256 every GENERATED-marked file (gate_m2_check.sh's technique) =="
MARKER="GENERATED by ggen"
find_manufactured() {
  for d in src lib test gleam/src gleam/test schema docs/reference; do
    [ -d "$d" ] || continue
    find "$d" -type f
  done | sort -u | while read -r f; do
    head -3 "$f" 2>/dev/null | grep -qi "$MARKER" && echo "$f"
  done
}
mapfile -t manufactured < <(find_manufactured)
for f in "${manufactured[@]}"; do shasum -a 256 "$f"; done | sort > "$WORK/baseline_sha.txt"
cp "$TARGET" "$WORK/baseline_beam4pm_types.ex"

echo "== 1. run the codemod (mix ggen_igniter.patch_field) =="
mix ggen_igniter.patch_field
cp "$TARGET" "$WORK/codemod_beam4pm_types.ex"

echo "== 2. zero changes elsewhere: re-hash every manufactured file, diff against the pre-patch baseline =="
for f in "${manufactured[@]}"; do shasum -a 256 "$f"; done | sort > "$WORK/post_codemod_sha.txt"

if diff -u "$WORK/baseline_sha.txt" "$WORK/post_codemod_sha.txt" | grep -v "^lib/beam4pm_types.ex$" | grep -qE "^[<>]"; then
  # Filter above intentionally allows lib/beam4pm_types.ex's hash line to
  # differ; anything else differing is a real regression.
  changed="$(diff "$WORK/baseline_sha.txt" "$WORK/post_codemod_sha.txt" | grep -E "^[<>]" | awk '{print $3}' | sort -u | grep -v '^lib/beam4pm_types\.ex$' || true)"
  if [ -n "$changed" ]; then
    echo "FAIL: codemod touched files outside lib/beam4pm_types.ex:"
    echo "$changed"
    exit 1
  fi
fi
echo "PASS: no manufactured file outside lib/beam4pm_types.ex changed"

echo "== 3. within lib/beam4pm_types.ex: every OTHER record-type module is byte-for-byte unchanged =="
split_modules() {
  awk -v outdir="$2" '
    /^defmodule BeamPM\.Types\./ {
      match($0, /BeamPM\.Types\.[A-Za-z0-9]+/)
      name = substr($0, RSTART+13, RLENGTH-13)
      out = outdir "/" name ".ex"
    }
    out { print > out }
  ' "$1"
}
mkdir -p "$WORK/baseline_modules" "$WORK/codemod_modules"
split_modules "$WORK/baseline_beam4pm_types.ex" "$WORK/baseline_modules"
split_modules "$WORK/codemod_beam4pm_types.ex" "$WORK/codemod_modules"

fail=0
for f in "$WORK"/baseline_modules/*.ex; do
  base="$(basename "$f")"
  [ "$base" = "DfgEdge.ex" ] && continue
  if ! diff -q "$f" "$WORK/codemod_modules/$base" >/dev/null 2>&1; then
    echo "FAIL: $base changed by the codemod but should be untouched"
    fail=1
  fi
done
[ "$fail" -eq 0 ] && echo "PASS: every other admitted bpm:RecordType module is byte-for-byte unchanged"
[ "$fail" -eq 0 ] || exit 1

echo "== 4. GENERATED provenance marker survives the patch =="
head -1 "$WORK/codemod_beam4pm_types.ex" | grep -qi "GENERATED by ggen" \
  && echo "PASS: GENERATED header present in codemod output" \
  || { echo "FAIL: GENERATED header missing"; exit 1; }

echo "== 5. codemod output vs a full ggen sync run from the same updated ontology.ttl (touched module only) =="
cp "$WORK/baseline_beam4pm_types.ex" "$TARGET"
rm -f ggen.lock
ggen sync run
cp "$TARGET" "$WORK/full_regen_beam4pm_types.ex"

extract_dfg_edge() {
  awk '/^defmodule BeamPM\.Types\.DfgEdge do$/{flag=1} flag{print} flag && /^end$/{exit}' "$1"
}
extract_dfg_edge "$WORK/codemod_beam4pm_types.ex" > "$WORK/codemod_dfgedge.ex"
extract_dfg_edge "$WORK/full_regen_beam4pm_types.ex" > "$WORK/full_regen_dfgedge.ex"

if diff -u "$WORK/full_regen_dfgedge.ex" "$WORK/codemod_dfgedge.ex"; then
  echo "PASS: codemod output for BeamPM.Types.DfgEdge is byte-identical to full ggen sync run regeneration"
else
  echo "FAIL: codemod output diverges from full regeneration for BeamPM.Types.DfgEdge"
  # restore codemod-patched state before exiting even on failure
  cp "$WORK/codemod_beam4pm_types.ex" "$TARGET"
  exit 1
fi

echo "B4PM-1702 verification: ALL CHECKS PASSED"
echo "(note: step 5's 'ggen sync run' regenerated the full manufactured tree"
echo " from the updated ontology.ttl as a verification side effect -- this is"
echo " expected and leaves the repo in the same fully-synced state a normal"
echo " 'just sync' would; lib/beam4pm_types.ex itself is confirmed identical"
echo " between that full regen and the codemod-only path above.)"
