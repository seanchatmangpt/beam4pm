#!/usr/bin/env bash
# GATE EVIDENCE COVERAGE -- every admitted bpm:EngineOp must have a real
# :telemetry.execute/3 evidence hook in its generated Elixir facade, or the
# tree is refused. This is a REGRESSION check against Phase 2's template
# change (beam4pm_engine.ex.tmpl), not an aspirational one: it greps the
# already-manufactured lib/beam4pm_<engine>.ex files for the emission this
# repo's own generator is supposed to have produced for every op.
#
# Mirrors scripts/gate_engine_dispatch_check.sh's shape and style (manifest
# read, per-row join, typed refusal codes, portable to bash 3.2, EXIT trap
# scratch dir) -- read that script first if editing this one.
#
# Scope of what a STATIC gate can prove, stated honestly per this repo's own
# no-overclaiming discipline (see docs/jira/v26.8.29 and
# scripts/gate_lint_truth.sh's banned-phrase list): this script can only
# ever populate two columns of the coverage matrix it writes --
#   declared   -- the op is an admitted bpm:EngineOp fact (from the manifest)
#   reachable  -- the generated Elixir facade contains a real
#                 :telemetry.execute([:beam4pm, :engine, <engine>, <op>], ...)
#                 call for it (grep evidence, not proof of runtime firing)
# It CANNOT populate, and does not claim to populate:
#   invoked    -- was the op actually called at runtime this run
#   ocel       -- did a real %BeamPM.Types.OcelEvent{} get buffered for it
#   otel       -- did a real OTel span get exported for it
#   verified   -- did BeamPM.ReceiptChain.verify/2 confirm a real chain link
#   receipted  -- was a real receipt JSON file written for it
# Those five columns require REAL runtime evidence (a real test/smoke run
# that exercises every op and inspects BeamPM.Ingest.Bridge.events(),
# exported OTel spans, and the receipt-chain directory) -- Phase 6's job,
# not this static gate's. This script writes those columns as the literal
# string "unverified_static_gate" so the matrix is never silently read as
# claiming runtime proof it doesn't have.
#
# Refusal codes (typed lines, any one fails the gate):
#   REFUSED_MANIFEST_MISSING / REFUSED_MANIFEST_UNMANUFACTURED / REFUSED_MANIFEST_MALFORMED
#   REFUSED_OP_NO_EVIDENCE_HOOK   an admitted op with no matching
#                                 :telemetry.execute([:beam4pm, :engine, E, OP], ...)
#                                 call in its generated lib/beam4pm_<engine>.ex
#   REFUSED_FACADE_ABSENT         the generated Elixir facade file is not on disk
#
# Portable to bash 3.2 on purpose (no mapfile, no associative arrays), same
# as scripts/gate_engine_dispatch_check.sh and scripts/gate_authorship_check.sh.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
MANIFEST=""
OUT=""
MARKER="GENERATED by ggen"

usage() {
  cat <<EOF
usage: bash scripts/gate_evidence_coverage_check.sh [--root DIR] [--manifest FILE] [--out FILE]
  --root DIR       repo working tree to check (default: this repo)
  --manifest FILE  engine-op manifest (default: <root>/schema/beam4pm_engine_ops.tsv)
  --out FILE       coverage-matrix output path (default: <root>/schema/beam4pm_evidence_coverage.tsv)
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --root) ROOT="$(cd "$2" && pwd)"; shift 2 ;;
    --manifest) MANIFEST="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "gate_evidence_coverage_check.sh: unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [ -z "$MANIFEST" ]; then
  MANIFEST="$ROOT/schema/beam4pm_engine_ops.tsv"
else
  case "$MANIFEST" in
    /*) ;;
    *) MANIFEST="$(pwd)/$MANIFEST" ;;
  esac
fi
if [ -z "$OUT" ]; then
  OUT="$ROOT/schema/beam4pm_evidence_coverage.tsv"
else
  case "$OUT" in
    /*) ;;
    *) OUT="$(pwd)/$OUT" ;;
  esac
fi

cd "$ROOT"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
FINDINGS="$WORK/findings"
ROWS="$WORK/rows"
MATRIX="$WORK/matrix"
: > "$FINDINGS"
: > "$MATRIX"

refuse() {
  if [ -n "${3:-}" ]; then
    echo "$1: $2 ($3)" >> "$FINDINGS"
  else
    echo "$1: $2" >> "$FINDINGS"
  fi
}

is_marked() {
  head -3 "$1" 2>/dev/null | grep -qi "$MARKER"
}

echo "== GATE EVIDENCE COVERAGE: admitted engine ops must have a real telemetry hook =="
echo "root: $ROOT"
echo "manifest: $MANIFEST"
echo "out: $OUT"

if [ ! -f "$MANIFEST" ]; then
  echo "REFUSED_MANIFEST_MISSING: $MANIFEST (regenerate: rm -f ggen.lock && ggen sync run)"
  echo "GATE EVIDENCE COVERAGE: FAIL -- engine-op manifest missing" >&2
  exit 1
fi
if ! is_marked "$MANIFEST"; then
  echo "REFUSED_MANIFEST_UNMANUFACTURED: $MANIFEST (no '$MARKER' marker in its first 3 lines)"
  echo "GATE EVIDENCE COVERAGE: FAIL -- engine-op manifest is not manufactured output" >&2
  exit 1
fi

grep -v '^#' "$MANIFEST" | grep -v '^[[:space:]]*$' > "$ROWS" || true
while IFS=$'\t' read -r engine op wire kind src artifact extra; do
  if [ -z "$engine" ] || [ -z "$op" ] || [ -z "$wire" ] || [ -z "$kind" ] || [ -z "$src" ] || [ -z "$artifact" ] || [ -n "${extra:-}" ]; then
    refuse REFUSED_MANIFEST_MALFORMED "$engine/$op" "expected exactly 6 tab-separated columns"
  fi
done < "$ROWS"
rows_n=$(wc -l < "$ROWS" | tr -d ' ')
engines_n=$(cut -f1 "$ROWS" | sort -u | wc -l | tr -d ' ')
echo "manifest: $rows_n ops across $engines_n engines"

{
  echo "# GENERATED by scripts/gate_evidence_coverage_check.sh -- do not hand-edit; re-run the gate to refresh."
  echo "# Coverage matrix: capability x declared/reachable (static, this gate) / invoked/ocel/otel/verified/receipted (runtime, Phase 6 only)."
  echo "# The five runtime columns are literally \"unverified_static_gate\" here -- this script has no runtime evidence to report."
  echo "# Columns (tab-separated): engine op declared reachable invoked ocel otel verified receipted"
} > "$MATRIX"

checked_n=0
declare_facade_cache="$WORK/facade_cache"
: > "$declare_facade_cache"

while IFS=$'\t' read -r engine op wire kind src artifact; do
  [ -n "$engine" ] || continue
  [ -n "$op" ] || continue
  facade="lib/beam4pm_${engine}.ex"
  if [ ! -f "$facade" ]; then
    refuse REFUSED_FACADE_ABSENT "$engine/$op" "$facade not on disk -- regenerate: rm -f ggen.lock && ggen sync run"
    printf '%s\t%s\tdeclared\tabsent\tunverified_static_gate\tunverified_static_gate\tunverified_static_gate\tunverified_static_gate\tunverified_static_gate\n' "$engine" "$op" >> "$MATRIX"
    continue
  fi
  checked_n=$((checked_n + 1))
  pattern="\\[:beam4pm, :engine, :${engine}, :${op}\\]"
  if grep -qE "$pattern" "$facade"; then
    reachable="reachable"
  else
    reachable="absent"
    refuse REFUSED_OP_NO_EVIDENCE_HOOK "$engine/$op" "no :telemetry.execute($pattern, ...) call in $facade -- Phase 2's template change has a gap for this op"
  fi
  printf '%s\t%s\tdeclared\t%s\tunverified_static_gate\tunverified_static_gate\tunverified_static_gate\tunverified_static_gate\tunverified_static_gate\n' \
    "$engine" "$op" "$reachable" >> "$MATRIX"
done < "$ROWS"

cp "$MATRIX" "$OUT"
echo "wrote coverage matrix: $OUT ($rows_n rows)"

findings_n=$(wc -l < "$FINDINGS" | tr -d ' ')
if [ "$findings_n" -gt 0 ]; then
  echo "REFUSED: $findings_n finding(s):"
  sort -u "$FINDINGS" | sed 's/^/  /'
  echo "GATE EVIDENCE COVERAGE: FAIL -- $findings_n finding(s)" >&2
  exit 1
fi

echo "GATE EVIDENCE COVERAGE: PASS -- $checked_n ops checked across $engines_n engines, 0 findings"
