defmodule BeamPM.PddlProjectionTest do
  @moduledoc """
  First executed instance of VISION-2030 section 10's relation
  `canonical graph -> formal projection -> planner result` (property S23,
  formal future search).

  The projection under test is manufactured, not hand-written: ggen renders
  `schema/pddl/<process_id>.domain.pddl` / `.problem.pddl` from the admitted
  `bpma:AdmittedActuation` and `bpmg:ProcessContract` individuals in
  `ontology.ttl` via `beam4pm-process-model-pack`'s
  `templates/beam4pm_pddl.{domain,problem}.pddl.tmpl`. This test reads those
  GENERATED files off disk (never a PDDL literal), feeds them to the REAL
  ferroplan planner hosted in BEAM (`BeamPM.Ferroplan.plan_production/4`,
  wasm collaborator, no mocks), and asserts on the decoded plan.

  Two independent projections of the same graph must agree: the planner's
  solved action sequence (from the ggen/Tera PDDL projection) must equal the
  ordinal `actuation_name` sequence in `BeamPM.ProcessGovernor.contracts/0`
  (the ggen_igniter/EEx Elixir projection). Neither side is hand-copied from
  the ontology here.

  Absence semantics mirror `BeamPM.FerroplanTest`: a missing wasm artifact is
  a NAMED SKIP on the planner-backed describes only; the pure file-shape
  assertions still run.
  """

  use ExUnit.Case, async: false

  alias BeamPM.Actuation
  alias BeamPM.Ferroplan
  alias BeamPM.ProcessGovernor

  @moduletag timeout: 120_000

  @pddl_dir Path.expand("schema/pddl")
  @marker "GENERATED by ggen"

  # -- helpers over the manufactured files --------------------------------

  defp contract_ids, do: ProcessGovernor.contracts() |> Map.keys() |> Enum.sort()

  defp contract(process_id), do: Map.fetch!(ProcessGovernor.contracts(), process_id)

  defp ordered_transitions(process_id),
    do: contract(process_id).transitions |> Enum.sort_by(& &1.ordinal)

  defp expected_sequence(process_id),
    do: ordered_transitions(process_id) |> Enum.map(& &1.actuation_name)

  defp domain_path(process_id), do: Path.join(@pddl_dir, "#{process_id}.domain.pddl")
  defp problem_path(process_id), do: Path.join(@pddl_dir, "#{process_id}.problem.pddl")

  defp read_pair(process_id),
    do: {File.read!(domain_path(process_id)), File.read!(problem_path(process_id))}

  defp domain_action_names(domain) do
    ~r/\(:action\s+([A-Za-z0-9_-]+)/
    |> Regex.scan(domain, capture: :all_but_first)
    |> List.flatten()
  end

  defp problem_allows_facts(problem) do
    ~r/\(allows_([A-Za-z0-9_-]+)\s+([A-Za-z0-9_-]+)\s+([A-Za-z0-9_-]+)\)/
    |> Regex.scan(problem, capture: :all_but_first)
    |> Enum.map(fn [action, from, to] -> {action, from, to} end)
  end

  defp allows_fact(%{actuation_name: a, from_state: f, to_state: t}),
    do: "(allows_#{a} #{f} #{t})"

  defp plan_steps(%{"payload" => %{"plan" => %{"steps" => steps}}}), do: steps

  defp step_action_names(envelope),
    do: envelope |> plan_steps() |> Enum.map(&String.downcase(&1["action"]))

  defp step_args(envelope),
    do: envelope |> plan_steps() |> Enum.map(fn s -> Enum.map(s["args"], &String.downcase/1) end)

  # -- the manufactured PDDL is a faithful projection of the admitted graph --

  describe "manufactured PDDL files" do
    test "every governed contract has a GENERATED domain + problem pair on disk" do
      ids = contract_ids()
      assert ids != []

      for id <- ids do
        assert File.exists?(domain_path(id)), "missing #{domain_path(id)}"
        assert File.exists?(problem_path(id)), "missing #{problem_path(id)}"

        {domain, problem} = read_pair(id)
        assert domain |> String.split("\n") |> hd() =~ @marker
        assert problem |> String.split("\n") |> hd() =~ @marker
      end
    end

    test "each domain's :action names are exactly the admitted bpma:actionName set" do
      admitted = Actuation.admitted_actuations() |> Map.keys() |> Enum.sort()
      assert admitted != []

      for id <- contract_ids() do
        {domain, _problem} = read_pair(id)
        assert Enum.sort(domain_action_names(domain)) == admitted
      end
    end

    test "each problem's allows_ facts are exactly the contract's transitions in ordinal order" do
      for id <- contract_ids() do
        {_domain, problem} = read_pair(id)

        expected =
          ordered_transitions(id)
          |> Enum.map(fn t -> {t.actuation_name, t.from_state, t.to_state} end)

        assert problem_allows_facts(problem) == expected
        assert problem =~ "(in_state #{contract(id).initial_state})"
        assert problem =~ "(:goal (in_state #{List.last(ordered_transitions(id)).to_state}))"
      end
    end

    test "every bpma:requiresFact of a named actuation is a domain precondition and a problem :init fact" do
      admitted = Actuation.admitted_actuations()

      for id <- contract_ids() do
        {domain, problem} = read_pair(id)

        for %{actuation_name: a} <- ordered_transitions(id),
            fact <- Map.fetch!(admitted, a).requires do
          [action_block] =
            Regex.run(~r/\(:action\s+#{Regex.escape(a)}\s.*?:effect/s, domain)

          assert action_block =~ "(#{fact})",
                 "#{id}.domain.pddl: action #{a} lacks precondition (#{fact})"

          assert problem =~ "(#{fact})",
                 "#{id}.problem.pddl: :init lacks required fact (#{fact})"
        end
      end
    end
  end

  # -- the real planner over the manufactured projection --------------------

  describe "planner result equals the contract's ordinal actuation sequence" do
    if not BeamPM.Ferroplan.wasm_built?() do
      @describetag skip: BeamPM.Ferroplan.wasm_missing_reason()
    end

    setup do
      {:ok, _pid} = Ferroplan.start()
      :ok
    end

    for process_id <- ["toy_counter_governed", "k8s_scaling_governed"] do
      @process_id process_id

      test "#{process_id}: plan_production/4 solves the GENERATED projection with the ordinal sequence" do
        id = @process_id
        {domain, problem} = read_pair(id)

        assert {:ok, envelope} = Ferroplan.plan_production(domain, problem)
        assert envelope["schema_version"] == "ferroplan.operation.v1"
        assert envelope["authority"] == "candidate_only"
        assert envelope["outcome"] == "solved"
        assert envelope["payload"]["solved"] == true

        expected = expected_sequence(id)
        assert expected != []
        assert step_action_names(envelope) == expected
        assert envelope["payload"]["plan"]["length"] == length(expected)

        # Each step's grounded arguments are the contract's own from/to states.
        expected_args =
          ordered_transitions(id) |> Enum.map(fn t -> [t.from_state, t.to_state] end)

        assert step_args(envelope) == expected_args
      end
    end

    test "the two contracts yield different plans from domains that admit the same action set" do
      {d1, p1} = read_pair("toy_counter_governed")
      {d2, p2} = read_pair("k8s_scaling_governed")
      assert Enum.sort(domain_action_names(d1)) == Enum.sort(domain_action_names(d2))

      assert {:ok, e1} = Ferroplan.plan_production(d1, p1)
      assert {:ok, e2} = Ferroplan.plan_production(d2, p2)
      assert e1["outcome"] == "solved" and e2["outcome"] == "solved"
      assert step_action_names(e1) != step_action_names(e2)

      assert MapSet.disjoint?(
               MapSet.new(step_action_names(e1)),
               MapSet.new(step_action_names(e2))
             )
    end
  end

  # -- an unlawful future is refused, never fabricated ---------------------

  describe "unlawful futures" do
    if not BeamPM.Ferroplan.wasm_built?() do
      @describetag skip: BeamPM.Ferroplan.wasm_missing_reason()
    end

    setup do
      {:ok, _pid} = Ferroplan.start()
      :ok
    end

    for process_id <- ["toy_counter_governed", "k8s_scaling_governed"] do
      @process_id process_id

      test "#{process_id}: deleting the final transition yields no_plan, not a fabricated plan" do
        id = @process_id
        {domain, problem} = read_pair(id)
        last = List.last(ordered_transitions(id))
        fact = allows_fact(last)
        assert problem =~ fact

        broken = String.replace(problem, fact, "")
        refute broken =~ fact

        assert {:ok, envelope} = Ferroplan.plan_production(domain, broken)
        assert envelope["outcome"] == "no_plan"
        assert envelope["payload"]["solved"] == false
        refute Map.has_key?(envelope["payload"], "plan")
        assert envelope["counters"]["grounded_actions"] == 0
      end

      test "#{process_id}: deleting the first transition yields no_plan, not a fabricated plan" do
        id = @process_id
        {domain, problem} = read_pair(id)
        first = List.first(ordered_transitions(id))
        fact = allows_fact(first)
        assert problem =~ fact

        assert {:ok, envelope} =
                 Ferroplan.plan_production(domain, String.replace(problem, fact, ""))

        assert envelope["outcome"] == "no_plan"
        assert envelope["payload"]["solved"] == false
        refute Map.has_key?(envelope["payload"], "plan")
      end
    end

    test "toy_counter_governed: removing the asserted requiresFact yields no_plan" do
      {domain, problem} = read_pair("toy_counter_governed")

      [fact] =
        ordered_transitions("toy_counter_governed")
        |> Enum.flat_map(fn t ->
          Map.fetch!(Actuation.admitted_actuations(), t.actuation_name).requires
        end)
        |> Enum.uniq()

      assert problem =~ "(#{fact})"
      stripped = String.replace(problem, "(#{fact})", "")

      assert {:ok, envelope} = Ferroplan.plan_production(domain, stripped)
      assert envelope["outcome"] == "no_plan"
      assert envelope["payload"]["solved"] == false
      refute Map.has_key?(envelope["payload"], "plan")
    end
  end
end
