  @doc "Every declared WASM engine, ordered by name."
  @spec engines() :: [engine()]
  def engines, do: @engines

  @doc "Every declared wire op across all engines, ordered by engine then op."
  @spec ops() :: [op()]
  def ops, do: @ops

  @doc "Ops belonging to one engine, by engine name."
  @spec ops_for(String.t()) :: [op()]
  def ops_for(engine) when is_binary(engine),
    do: Enum.filter(@ops, &(&1.engine == engine))

  @doc "Look up one engine by name."
  @spec engine(String.t()) :: engine() | nil
  def engine(name) when is_binary(name),
    do: Enum.find(@engines, &(&1.name == name))

  @doc "Look up one op by engine name and wire op name."
  @spec op(String.t(), String.t()) :: op() | nil
  def op(engine, name) when is_binary(engine) and is_binary(name),
    do: Enum.find(@ops, &(&1.engine == engine and &1.op == name))

  @doc "Ops classified as observational (`:read`)."
  @spec read_ops() :: [op()]
  def read_ops, do: Enum.filter(@ops, &(&1.consequence == :read))

  @doc "Ops that mutate in-engine wasm state (`:do`). Still not host authority."
  @spec do_ops() :: [op()]
  def do_ops, do: Enum.filter(@ops, &(&1.consequence == :do))

  @doc "Ops that mint a handle the caller must eventually free."
  @spec handle_minting_ops() :: [op()]
  def handle_minting_ops, do: Enum.filter(@ops, & &1.handle_returning?)

  @doc "Ops that free a handle."
  @spec handle_freeing_ops() :: [op()]
  def handle_freeing_ops, do: Enum.filter(@ops, & &1.frees_handle?)

  @doc "The per-op default timeout in ms, resolved against its engine's class defaults."
  @spec timeout_ms(String.t(), String.t()) :: pos_integer() | nil
  def timeout_ms(engine_name, op_name) do
    with %{} = e <- engine(engine_name),
         %{} = o <- op(engine_name, op_name) do
      if o.timeout_class == :heavy, do: e.heavy_timeout_ms, else: e.cheap_timeout_ms
    else
      _ -> nil
    end
  end

  @doc "Counts, for drift checks against the ontology and the README."
  @spec stats() :: %{engines: non_neg_integer(), ops: non_neg_integer(), read: non_neg_integer(), do: non_neg_integer()}
  def stats do
    %{
      engines: length(@engines),
      ops: length(@ops),
      read: length(read_ops()),
      do: length(do_ops())
    }
  end
