defmodule Beam4pm.MixProject do
  use Mix.Project

  def project do
    [
      app: :beam4pm,
      # Must match src/beam4pm.app.src's {vsn, ...} tuple -- bump both
      # together via `mix beam4pm.version_bump <version>`
      # (lib/mix/tasks/beam4pm.version_bump.ex), never by hand-editing one
      # without the other.
      version: "26.9.30",
      elixir: "~> 1.17",
      start_permanent: Mix.env() == :prod,
      deps: deps(),
      aliases: aliases(),
      description: description(),
      package: package(),
      source_url: "https://github.com/seanchatmangpt/beam4pm",
      homepage_url: "https://github.com/seanchatmangpt/beam4pm",
      docs: docs()
    ]
  end

  defp description do
    "A BEAM-first process-mining substrate manufactured entirely by ggen " <>
      "from ontology.ttl + a vendored ggen-marketplace pack: real OCEL " <>
      "discovery/conformance across Erlang, Elixir, Gleam, and Ash " <>
      "projections, plus native engine facades (petgraph, tract, rust4pm, " <>
      "ferroplan) hosted in BEAM via wasm."
  end

  defp package do
    [
      licenses: ["Apache-2.0"],
      links: %{"GitHub" => "https://github.com/seanchatmangpt/beam4pm"},
      files:
        ~w(lib src schema gleam native/graphlaw mix.exs rebar.config ontology.ttl ggen.toml README.md CONTRIBUTING.md CLAUDE.md)
    ]
  end

  defp docs do
    [
      main: "readme",
      extras: ["README.md"]
    ]
  end

  def application do
    [
      mod: {BeamPM.Application, []},
      extra_applications: [:logger]
    ]
  end

  def cli do
    [preferred_envs: ["test.chicago": :test]]
  end

  # lib/ and test/ hold hand-authored and ggen-manufactured source alike --
  # standard Mix defaults (compile all of lib/, run all of test/), no custom
  # elixirc_paths/test_paths needed. Manufactured provenance is signalled
  # per-file by the "GENERATED by ggen ... Do not edit." header comment,
  # never by directory placement. See CONTRIBUTING.md.

  # :ggen_igniter is a manufacturing-time tool only (`mix ggen_igniter.sync`,
  # see scripts/igniter_sync.sh) -- never a runtime dependency of generated
  # code. Compiling it requires a working Rust/cargo toolchain (its default
  # oxigraph query engine is a Rustler NIF). :ash IS a real runtime
  # dependency of the manufactured lib/beam4pm_ash.ex. :wasmex hosts the ONE
  # process-mining engine (rust4pm compiled to wasm32-wasip1, see
  # native/rust4pm-wasm/ and lib/beam4pm_rust4pm.ex); Elixir/Erlang/Gleam are
  # facades over it, so it is a runtime dep like :ash, not a
  # manufacturing-time dep like :ggen_igniter.
  defp deps do
    [
      {:ggen_igniter, "~> 26.9", runtime: false},
      # Match ash_ai's real lower bound and make the direct dependency authoritative.
      # This also refuses the stale deps/ash 3.33.1 tree observed in CI while
      # mix.lock pins 3.33.9, instead of letting restored cache state override the lock.
      ash_dep(),
      {:ash_ai, "~> 1.0"},
      {:wasmex, "~> 0.15"},
      # OCEL evidence-contract phases 2-3: telemetry events + OTel span bridge
      # (lib/beam4pm_evidence.ex).
      {:telemetry, "~> 1.4"},
      {:opentelemetry, "~> 1.5"},
      {:opentelemetry_api, "~> 1.4"},
      # BeamPM.OcelIngest.Router (lib/beam4pm_ocel_ingest.ex) -- beam4pm's own
      # independent network ingestion layer, real runtime deps (not
      # only: :test): a running beam4pm needs to actually listen.
      {:plug, "~> 1.14"},
      {:bandit, "~> 1.5"},
      # Agent-facing layer only (see docs/jira -- A2A does not replace or
      # touch beam4pm's internal mechanisms: EngineOp dispatch, OCEL/OTel
      # evidence chain, BeamPM.ReceiptChain). Additive alongside ex4pm's
      # existing Ex4pm.Engine.Beam4pm HTTP route-table client.
      ash_a2a_dep(),
      {:a2a, "~> 0.1"},
      {:req, "~> 0.5"},
      {:ex_doc, ">= 0.0.0", only: :dev, runtime: false}
    ]
  end

  # Hex refuses overridden and git dependencies. Normal development keeps the
  # override (stale deps/ash cache guard) and the pinned ash_a2a git ref;
  # `BEAM4PM_HEX_PUBLISH=1 mix hex.build` / `mix hex.publish` swaps in the
  # published releases. ash_a2a 26.9.30 must be on Hex before beam4pm 26.9.30
  # can be published: Replan.Loop and Replan.ProviderRegistry first ship there.
  defp hex_publish?, do: System.get_env("BEAM4PM_HEX_PUBLISH") in ["1", "true"]

  defp ash_dep do
    if hex_publish?(),
      do: {:ash, ">= 3.33.6 and < 4.0.0-0"},
      else: {:ash, ">= 3.33.6 and < 4.0.0-0", override: true}
  end

  defp ash_a2a_dep do
    if hex_publish?() do
      {:ash_a2a, "~> 26.9.30"}
    else
      {:ash_a2a,
       git: "https://github.com/seanchatmangpt/ash_a2a.git",
       ref: "80b77e225814d7a10a724e5ac01318600c71ee4c",
       override: true}
    end
  end

  # `mix test` (default, test/test_helper.exs excludes :chicago) -- fast,
  # everyday loop. `mix test.chicago` -- full suite including any test
  # explicitly tagged :chicago (a repo-wide convention for slow,
  # full-integration-scope cases; no test currently carries the tag here,
  # so this alias is presently equivalent to `mix test --include chicago`
  # with nothing extra admitted -- it exists as the standing seam for the
  # first real :chicago-tagged integration test, not a currently-populated
  # suite).
  defp aliases do
    [
      "test.chicago": ["test --include chicago"]
    ]
  end
end
